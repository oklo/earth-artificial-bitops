"""Physical constants and energy thresholds used by the bitops model."""

from __future__ import annotations

import math

BOLTZMANN_J_PER_K = 1.380_649e-23
TEMPERATURE_K = 300.0
LN2 = math.log(2.0)
LANDAUER_J_PER_BIT_300K = BOLTZMANN_J_PER_K * TEMPERATURE_K * LN2

SECONDS_PER_JULIAN_YEAR = 365.25 * 24.0 * 3600.0

CURRENT_GLOBAL_PRIMARY_ENERGY_W = 650.0e18 / SECONDS_PER_JULIAN_YEAR
EARTH_INTERCEPTED_SOLAR_W = 1.74e17
SOLAR_LUMINOSITY_W = 3.828e26

CURRENT_INCLUSIVE_BITOPS_PER_S = 1.0399404071682317e26
CURRENT_NON_POW_BITOPS_PER_S = 1.35229561654737e24
CURRENT_INCLUSIVE_LANDAUER_EFFICIENCY = 1.6332937679407356e-6
CURRENT_NON_POW_LANDAUER_EFFICIENCY = 2.5569315757195548e-8

CURRENT_INCLUSIVE_POWER_W = (
    CURRENT_INCLUSIVE_BITOPS_PER_S
    * LANDAUER_J_PER_BIT_300K
    / CURRENT_INCLUSIVE_LANDAUER_EFFICIENCY
)
